//   })

import type { ProSiteFeatureTab } from '../shared/types'
import { addComponent, addImportsDir, addTemplate, createResolver, defineNuxtModule } from 'nuxt/kit'
import { proSiteFeatureNavOrder } from '../shared/manifest'

/** Every page under this prefix renders inside the dashboard shell. */
const DASHBOARD_PREFIX = '/pro/dashboard'
const DASHBOARD_LAYOUT = 'pro-dashboard'

export default defineNuxtModule({
  meta: {
    name: 'pro-features',
    configKey: 'proFeatures',
  },
  setup(_options, nuxt) {
    const resolver = createResolver(import.meta.url)
    const manifestSource = resolver.resolve('../shared/manifest.ts')

    // Force eager page-meta scan so `pages:extend` sees `proTab` from
    // definePageMeta. Default is 'after-resolve' which fires too late.
    nuxt.options.experimental ||= {} as never
    const experimental = nuxt.options.experimental as Record<string, unknown>
    experimental.scanPageMeta = true
    // `layout` is not one of Nuxt's default extraction keys, so without this a
    // page that declares its own layout looks layout-less to the hook below and
    // gets the dashboard shell it did not ask for. Declared here rather than in
    // the layer's nuxt.config because a layer's `experimental` block does not
    // survive the merge with the root config.
    const extractionKeys = (experimental.extraPageMetaExtractionKeys as string[] | undefined) ?? []
    experimental.extraPageMetaExtractionKeys = Array.from(new Set([...extractionKeys, 'proTab', 'pro', 'layout']))

    const tabsByFeature = new Map<string, ProSiteFeatureTab[]>()

    nuxt.hook('pages:extend', (pages) => {
      tabsByFeature.clear()
      const join = (parent: string, child: string) => {
        if (!child)
          return parent
        if (child.startsWith('/'))
          return child
        return `${parent.replace(/\/$/, '')}/${child}`
      }
      const walk = (list: typeof pages, parentPath: string) => {
        for (const page of list) {
          const absPath = join(parentPath, page.path ?? '')
          const meta = (page.meta ?? {}) as { proTab?: Omit<ProSiteFeatureTab, 'to'> }
          if (meta.proTab) {
            const tab: ProSiteFeatureTab = {
              feature: meta.proTab.feature,
              label: meta.proTab.label,
              icon: meta.proTab.icon,
              order: meta.proTab.order ?? 100,
              to: absPath,
            }
            const list = tabsByFeature.get(tab.feature) ?? []
            list.push(tab)
            tabsByFeature.set(tab.feature, list)
          }
          // Every dashboard page renders in the shell. Assigning it here keeps
          // the feature layers out of it: a page that does declare a layout
          // (the focused account shell) keeps the one it declared.
          if (absPath.startsWith(DASHBOARD_PREFIX)) {
            page.meta ||= {}
            page.meta.layout ??= DASHBOARD_LAYOUT
          }
          if (page.children?.length)
            walk(page.children, absPath)
        }
      }
      walk(pages, '')
      for (const list of tabsByFeature.values())
        list.sort((a, b) => a.order - b.order)
    })

    // The static nav manifest reaches BOTH the app and the Nitro graph through
    // one virtual, so a server handler and the sidebar resolve the same row.
    addTemplate({
      filename: 'pro-features/manifest.mjs',
      write: true,
      getContents: () => [
        `// Auto-generated by pro-features. Do not edit.`,
        `export * from ${JSON.stringify(manifestSource)}`,
      ].join('\n'),
    })

    addTemplate({
      filename: 'pro-features/manifest.d.ts',
      write: true,
      getContents: () => `export * from '${manifestSource.replace(/\.ts$/, '')}'`,
    })

    addTemplate({
      filename: 'pro-features/tabs.mjs',
      write: true,
      getContents: () => {
        const obj = Object.fromEntries(tabsByFeature)
        return [
          `// Auto-generated by pro-features. Do not edit.`,
          `export const tabsByFeature = ${JSON.stringify(obj, null, 2)}`,
          `export const topNavOrder = ${JSON.stringify(proSiteFeatureNavOrder)}`,
        ].join('\n')
      },
    })

    addTemplate({
      filename: 'pro-features/tabs.d.ts',
      write: true,
      getContents: () => [
        `import type { ProSiteFeatureTab } from '${resolver.resolve('../shared/types')}'`,
        `export declare const tabsByFeature: Record<string, ProSiteFeatureTab[]>`,
        `export declare const topNavOrder: string[]`,
      ].join('\n'),
    })

    nuxt.options.alias['#pro-features/manifest'] = resolver.resolve(nuxt.options.buildDir, 'pro-features/manifest.mjs')
    nuxt.options.alias['#pro-features/tabs'] = resolver.resolve(nuxt.options.buildDir, 'pro-features/tabs.mjs')

    addImportsDir(resolver.resolve('../app/composables'))
    addComponent({
      name: 'ProSiteFeaturePage',
      filePath: resolver.resolve('../app/components/pro-features/ProSiteFeaturePage.vue'),
    })
    addComponent({
      name: 'ProSurfacePlaceholder',
      filePath: resolver.resolve('../app/components/pro-features/ProSurfacePlaceholder.vue'),
    })
  },
})
