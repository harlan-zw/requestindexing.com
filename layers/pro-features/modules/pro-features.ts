// Build-time module for pro-features.
//
// Three build-time jobs:
//
//   1. Publish the static nav manifest (`shared/manifest.ts`) as
//      `#pro-features/manifest`, to the app AND the Nitro graph, the way
//      nuxtseo.com's pro-features module does. Identity, route, group and
//      order are manifest facts; the sidebar derives, it does not declare.
//   2. Give every `/pro/dashboard/**` page the dashboard layout, so a feature
//      layer never has to remember the shell.
//   3. Collect `proTab` page meta into `#pro-features/tabs.mjs`.
//
// Everything else (state resolvers, chrome components) is registered at
// runtime via the `pro:feature` hook from each layer's
// `app/plugins/pro-feature.ts`. See ADR-0015 (modernized).
//
// Each pro-* layer plugin looks like:
//
//   import { useGscFeatureDataState } from '../composables/...'
//   import ProGscFeatureChrome from '../internal/components/...'
//
//   export default defineNuxtPlugin({
//     name: 'pro-gsc:feature',
//     setup(nuxtApp) {
//       nuxtApp.hook('pro:feature', (registry) => {
//         registry.add({
//           id: 'search-console',
//           ...
//           stateResolver: siteId => useGscFeatureDataState(siteId, { includeStale: true }),
//         })
//         registry.addChrome({
//           forFeatures: ['search-console', 'indexing', 'analysis'],
//           component: ProGscFeatureChrome,
//         })
//       })
